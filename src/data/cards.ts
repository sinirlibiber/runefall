// 30-card deck list shared by both duelists (2 copies of most, 1 of the
// expensive top-end) so matches stay balanced and readable.
export function buildDeck(): string[] {
  const twoCopies = [
    "ember_whelp",
    "ashfall_scout",
    "spark_imp",
    "runic_shield",
    "rune_acolyte",
    "frost_sprite",
    "wardens_blade",
    "cinder_hound",
    "stonebound_guardian",
    "ashen_priest",
    "rune_of_renewal",
    "emberstorm",
    "thunder_warden",
    "wraith_of_ashveil",
  ];
  const oneCopy = ["bonewind_caller", "voidbind_sentinel", "skyrend_drake", "flameheart_colossus"];
  const deck: string[] = [];
  twoCopies.forEach((id) => deck.push(id, id));
  oneCopy.forEach((id) => deck.push(id));
  return deck;
}

export function shuffle<T>(arr: T[]): T[] {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}
